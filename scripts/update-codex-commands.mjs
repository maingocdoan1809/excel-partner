#!/usr/bin/env node
// Refresh the TUI catalog from the official source matching the installed CLI.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import spawn from "cross-spawn";

const installed = process.argv[2] ? undefined : spawn.sync(process.env.CODEX_BIN ?? "codex", ["--version"], { encoding: "utf8", windowsHide: true });
const version = process.argv[2] ?? /\b(\d+\.\d+\.\d+)\b/.exec(installed?.stdout ?? "")?.[1];
if (!version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error("Pass a Codex version, e.g. npm run update:codex-commands -- 0.164.0");
const ref = `rust-v${version}`;
const url = `https://raw.githubusercontent.com/openai/codex/${ref}/codex-rs/tui/src/slash_command.rs`;
const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
if (!response.ok) throw new Error(`Could not fetch Codex ${version}: HTTP ${response.status}`);
const source = await response.text();
const body = source.split("pub enum SlashCommand {")[1]?.split("\n}")[0];
if (!body) throw new Error("Codex changed its command source format. Review the generator before updating.");

const native = new Set(["skills", "compact", "review", "rename", "mcp", "apps", "ps", "stop", "pwd", "status", "usage", "plan", "goal", "hooks", "fork"]);
const client = new Set(["clear", "new", "resume", "model", "permissions", "copy", "export", "theme"]);
const hints = { skills: "list | <name> <request>", review: "uncommitted | branch <name> | commit <sha> | <instructions>",
  rename: "<title>", plan: "on | off | <task>", goal: "<objective> | clear", fork: "<optional title>" };
const commands = [];
let attributes = "";
for (const line of body.split("\n")) {
  if (line.trim().startsWith("#[")) { attributes += ` ${line.trim()}`; continue; }
  const match = /^\s*([A-Za-z]+),/.exec(line);
  if (!match) continue;
  const variant = match[1];
  const alias = /(?:to_string|serialize)\s*=\s*"([^"]+)"/.exec(attributes);
  const name = alias?.[1] ?? variant.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
  attributes = "";
  if (["test-approval", "rollout", "debug-m-drop", "debug-m-update"].includes(name)) continue;
  const description = new RegExp(`SlashCommand::${variant}(?:\\s*\\|\\s*SlashCommand::\\w+)*\\s*=>\\s*(?:\\{\\s*)?"([^"\\n]*)"`).exec(source)?.[1] ?? name.replaceAll("-", " ");
  const execution = native.has(name) || client.has(name) ? "native" : "unsupported";
  commands.push({ name, description, execution, ...(hints[name] ? { inputHint: hints[name] } : {}),
    ...(execution === "unsupported" ? { reason: "Requires a Codex-specific interface; run this command in the Codex terminal." } : {}) });
}
if (commands.length < 20 || new Set(commands.map(command => command.name)).size !== commands.length) throw new Error("Unexpected Codex catalog. Existing file was preserved.");
const output = `// Generated by scripts/update-codex-commands.mjs from ${url}\nimport { normalizeCommands } from "./commands.js";\nexport const CODEX_COMMAND_CATALOG_VERSION = "${version}";\nexport const CODEX_COMMANDS = normalizeCommands(${JSON.stringify(commands, null, 2)});\n`;
fs.writeFileSync(fileURLToPath(new URL("../providers/src/codex-commands.ts", import.meta.url)), output);
console.log(`Updated ${commands.length} commands from Codex ${version}.`);

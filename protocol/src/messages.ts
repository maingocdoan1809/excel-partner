import { z } from "zod";
import { ProviderIdSchema, ProviderDetectionSchema } from "./providers.js";
import { ProviderEventSchema } from "./events.js";
import { SelectionSnapshotSchema, ToolResultSchema } from "./tool-results.js";

/* -------------------------------------------------------------------------- */
/* Client -> Bridge                                                            */
/* -------------------------------------------------------------------------- */

export const ClientInfoSchema = z.object({
  excelVersion: z.string().nullable().optional(),
  platform: z.string().nullable().optional(),
  locale: z.string().nullable().optional(),
  addinVersion: z.string().nullable().optional(),
});
export type ClientInfo = z.infer<typeof ClientInfoSchema>;

export const HelloMessageSchema = z.object({
  type: z.literal("hello"),
  protocolVersion: z.number().int().positive(),
  /**
   * Random id generated by the task pane per connection. The file path is NOT
   * used because the workbook may be unsaved or renamed.
   */
  workbookConnectionId: z.string().min(8).max(128),
  clientInfo: ClientInfoSchema.optional(),
});

export const SetProviderMessageSchema = z.object({
  type: z.literal("set_provider"),
  provider: ProviderIdSchema,
});

export const ToolCapabilitiesSchema = z.object({
  webSearch: z.boolean().default(false),
  playwright: z.boolean().default(false),
});
export type ToolCapabilities = z.infer<typeof ToolCapabilitiesSchema>;

export const PromptMessageSchema = z.object({
  type: z.literal("prompt"),
  requestId: z.string().min(1),
  prompt: z.string().min(1).max(32_000),
  /** Execute a discovered provider command without prompt/context expansion. */
  command: z.boolean().optional(),
  chatSessionId: z.string().min(1).max(160).optional(),
  /** Native provider session to resume; never silently replaced with a new session. */
  resumeSessionId: z.string().regex(/^[a-zA-Z0-9_-]{1,128}$/).optional(),
  /** Explicit CLI model ID; omitted for the provider's configured default. */
  model: z.string().regex(/^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,79}$/).nullable().optional(),
  effort: z.enum(["low", "medium", "high"]).optional(),
  capabilities: ToolCapabilitiesSchema.optional(),
  /** Snapshot of the live selection captured when the user hit send. */
  selection: SelectionSnapshotSchema.nullable(),
  /** Earlier conversation replayed as context when a past chat is continued (the provider has no memory of it). */
  context: z.string().max(24_000).optional(),
  /** Legacy in-memory attachments; the task pane uses referencePaths for new selections. */
  attachmentIds: z.array(z.string().uuid()).max(10).optional(),
  /** Exact local files chosen by the user; the bridge validates each path against session grants. */
  referencePaths: z.array(z.string().min(1).max(500)).max(10).optional(),
});

export const CancelMessageSchema = z.object({
  type: z.literal("cancel"),
  requestId: z.string().min(1),
});
export const FollowupMessageSchema = z.object({
  type: z.literal("followup"),
  requestId: z.string().min(1),
  id: z.string().min(1).max(128),
  prompt: z.string().min(1).max(32_000),
  referencePaths: z.array(z.string().min(1).max(500)).max(10).optional(),
  attachmentIds: z.array(z.string().uuid()).max(10).optional(),
});

export const ToolResultMessageSchema = z.object({
  type: z.literal("tool_result"),
  callId: z.string().min(1),
  result: ToolResultSchema,
});

export const ClientPongSchema = z.object({
  type: z.literal("pong"),
  nonce: z.string(),
});

export const ClientMessageSchema = z.discriminatedUnion("type", [
  HelloMessageSchema,
  SetProviderMessageSchema,
  PromptMessageSchema,
  CancelMessageSchema,
  FollowupMessageSchema,
  ToolResultMessageSchema,
  ClientPongSchema,
]);
export type ClientMessage = z.infer<typeof ClientMessageSchema>;

/* -------------------------------------------------------------------------- */
/* Bridge -> Client                                                            */
/* -------------------------------------------------------------------------- */

export const HelloOkMessageSchema = z.object({
  type: z.literal("hello_ok"),
  protocolVersion: z.number().int().positive(),
  sessionToken: z.string().min(16),
  workbookConnectionId: z.string(),
  serverTime: z.string(),
  /** Identifies the task pane bundle the bridge currently serves; a pane running another one reloads itself. */
  addinBuildId: z.string().optional(),
});

export type HelloOkMessage = z.infer<typeof HelloOkMessageSchema>;

export const HelloErrorMessageSchema = z.object({
  type: z.literal("hello_error"),
  code: z.enum(["protocol_mismatch", "invalid_hello", "session_limit", "rejected"]),
  message: z.string(),
});
export type HelloErrorMessage = z.infer<typeof HelloErrorMessageSchema>;

export const ProviderStatusMessageSchema = z.object({
  type: z.literal("provider_status"),
  provider: ProviderIdSchema,
  detection: ProviderDetectionSchema,
});
export type ProviderStatusMessage = z.infer<typeof ProviderStatusMessageSchema>;

/** Bridge asks the task pane to execute one Excel tool via Office.js. */
export const ToolRequestMessageSchema = z.object({
  type: z.literal("tool_request"),
  requestId: z.string(),
  callId: z.string(),
  tool: z.string(),
  args: z.unknown(),
  /** Milliseconds the pane has to answer before the bridge times out. */
  timeoutMs: z.number().int().positive(),
});
export type ToolRequestMessage = z.infer<typeof ToolRequestMessageSchema>;

export const PingMessageSchema = z.object({
  type: z.literal("ping"),
  nonce: z.string(),
});

export const ServerMessageSchema = z.union([
  z.object({ type: z.literal("user_input_closed"), callId: z.string() }),
  HelloOkMessageSchema,
  HelloErrorMessageSchema,
  ProviderStatusMessageSchema,
  ToolRequestMessageSchema,
  PingMessageSchema,
  ...ProviderEventSchema.options,
]);
export type ServerMessage = z.infer<typeof ServerMessageSchema>;

export function encodeMessage(message: ClientMessage | ServerMessage): string {
  return JSON.stringify(message);
}

export function decodeServerMessage(raw: string): ServerMessage {
  return ServerMessageSchema.parse(JSON.parse(raw));
}

export function decodeClientMessage(raw: string): ClientMessage {
  return ClientMessageSchema.parse(JSON.parse(raw));
}

import { z } from "zod";
import { ProviderIdSchema, ProviderDetectionSchema } from "./providers.js";
import { ProviderEventSchema } from "./events.js";
import { AnySelectionSnapshotSchema, ToolResultSchema } from "./tool-results.js";
import { HostIdSchema } from "./host.js";
import { MAX_DELEGATED_TEXT } from "./tools-advanced.js";

/* -------------------------------------------------------------------------- */
/* Client -> Bridge                                                            */
/* -------------------------------------------------------------------------- */

export const ClientInfoSchema = z.object({
  excelVersion: z.string().nullable().optional(),
  platform: z.string().nullable().optional(),
  locale: z.string().nullable().optional(),
  addinVersion: z.string().nullable().optional(),
  /** The pane is open in a browser tab, not in Excel: there is no workbook behind it. */
  standalone: z.boolean().optional(),
  /** The Office application the pane runs in. Panes that predate multi-host support are Excel. */
  host: HostIdSchema.default("excel"),
});
export type ClientInfo = z.infer<typeof ClientInfoSchema>;
/** What a pane may send: `host` can be left out and is then Excel. */
export type ClientInfoInput = z.input<typeof ClientInfoSchema>;

export const HelloMessageSchema = z.object({
  type: z.literal("hello"),
  protocolVersion: z.number().int().positive(),
  /**
   * Random id generated by the task pane per connection. The file path is NOT
   * used because the workbook may be unsaved or renamed.
   */
  workbookConnectionId: z.string().min(8).max(128),
  clientInfo: ClientInfoSchema.optional(),
});

/** The workbook's current name, sent after the handshake and whenever it changes (Save As, rename). */
export const WorkbookInfoMessageSchema = z.object({
  type: z.literal("workbook_info"),
  name: z.string().trim().min(1).max(255),
});

/**
 * The pane wants the list of connected files to be current (it opened the list). The bridge asks every pane for its
 * workbook's name right now and sends `connected_files` to all of them.
 */
export const RefreshConnectedFilesMessageSchema = z.object({
  type: z.literal("refresh_connected_files"),
});

/**
 * Pseudo tool the bridge sends to a pane to ask for its workbook's current name. The pane answers
 * `{ ok: true, data: { name: string | null } }`. A name has no change event in Excel, so it is read when someone needs it.
 */
export const WORKBOOK_NAME_REQUEST = "__workbook_name";

/**
 * Pseudo tool the bridge sends to a pane to show a range in its workbook: `{ sheet?, address }`. Sent when someone follows a
 * link in another file's chat. It only moves the selection; the pane answers `{ ok: true, data: {} }` or the reason it could not.
 */
export const GO_TO_REQUEST = "__go_to";

export const SetProviderMessageSchema = z.object({
  type: z.literal("set_provider"),
  provider: ProviderIdSchema,
});

export const ToolCapabilitiesSchema = z.object({
  webSearch: z.boolean().default(false),
  playwright: z.boolean().default(false),
});
export type ToolCapabilities = z.infer<typeof ToolCapabilitiesSchema>;

export const PromptMessageSchema = z.object({
  type: z.literal("prompt"),
  requestId: z.string().min(1),
  prompt: z.string().min(1).max(32_000),
  /** Execute a discovered provider command without prompt/context expansion. */
  command: z.boolean().optional(),
  chatSessionId: z.string().min(1).max(160).optional(),
  /** Native provider session to resume; never silently replaced with a new session. */
  resumeSessionId: z.string().regex(/^[a-zA-Z0-9_-]{1,128}$/).optional(),
  /** Explicit CLI model ID; omitted for the provider's configured default. */
  model: z.string().regex(/^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,79}$/).nullable().optional(),
  effort: z.enum(["low", "medium", "high"]).optional(),
  capabilities: ToolCapabilitiesSchema.optional(),
  /** Snapshot of the live selection captured when the user hit send. */
  selection: AnySelectionSnapshotSchema.nullable(),
  /** Earlier conversation replayed as context when a past chat is continued (the provider has no memory of it). */
  context: z.string().max(24_000).optional(),
  /** Legacy in-memory attachments; the task pane uses referencePaths for new selections. */
  attachmentIds: z.array(z.string().uuid()).max(10).optional(),
  /** Exact local files chosen by the user; the bridge validates each path against session grants. */
  referencePaths: z.array(z.string().min(1).max(500)).max(10).optional(),
  /** Set when this turn answers a request another file's assistant sent (see `delegated_prompt`). */
  delegationId: z.string().min(1).max(64).optional(),
});

/** The task pane cannot take a request another workbook's assistant sent (busy, not ready). */
export const DelegationDeclinedMessageSchema = z.object({
  type: z.literal("delegation_declined"),
  delegationId: z.string().min(1).max(64),
  reason: z.string().max(200),
});

export const CancelMessageSchema = z.object({
  type: z.literal("cancel"),
  requestId: z.string().min(1),
});
export const FollowupMessageSchema = z.object({
  type: z.literal("followup"),
  requestId: z.string().min(1),
  id: z.string().min(1).max(128),
  prompt: z.string().min(1).max(32_000),
  referencePaths: z.array(z.string().min(1).max(500)).max(10).optional(),
  attachmentIds: z.array(z.string().uuid()).max(10).optional(),
});

export const ToolResultMessageSchema = z.object({
  type: z.literal("tool_result"),
  callId: z.string().min(1),
  result: ToolResultSchema,
});

export const ClientPongSchema = z.object({
  type: z.literal("pong"),
  nonce: z.string(),
});

export const ClientMessageSchema = z.discriminatedUnion("type", [
  HelloMessageSchema,
  WorkbookInfoMessageSchema,
  RefreshConnectedFilesMessageSchema,
  SetProviderMessageSchema,
  PromptMessageSchema,
  DelegationDeclinedMessageSchema,
  CancelMessageSchema,
  FollowupMessageSchema,
  ToolResultMessageSchema,
  ClientPongSchema,
]);
export type ClientMessage = z.infer<typeof ClientMessageSchema>;
/** A client message as a pane may build it: `clientInfo.host` and `selection.host` can be left out (they mean Excel). */
export type ClientMessageInput = z.input<typeof ClientMessageSchema>;

/* -------------------------------------------------------------------------- */
/* Bridge -> Client                                                            */
/* -------------------------------------------------------------------------- */

export const HelloOkMessageSchema = z.object({
  type: z.literal("hello_ok"),
  protocolVersion: z.number().int().positive(),
  sessionToken: z.string().min(16),
  workbookConnectionId: z.string(),
  serverTime: z.string(),
  /** Identifies the task pane bundle the bridge currently serves; a pane running another one reloads itself. */
  addinBuildId: z.string().optional(),
});

export type HelloOkMessage = z.infer<typeof HelloOkMessageSchema>;

export const HelloErrorMessageSchema = z.object({
  type: z.literal("hello_error"),
  code: z.enum(["protocol_mismatch", "invalid_hello", "session_limit", "rejected"]),
  message: z.string(),
});
export type HelloErrorMessage = z.infer<typeof HelloErrorMessageSchema>;

export const ProviderStatusMessageSchema = z.object({
  type: z.literal("provider_status"),
  provider: ProviderIdSchema,
  detection: ProviderDetectionSchema,
});
export type ProviderStatusMessage = z.infer<typeof ProviderStatusMessageSchema>;

/** Bridge asks the task pane to execute one Excel tool via Office.js. */
export const ToolRequestMessageSchema = z.object({
  type: z.literal("tool_request"),
  requestId: z.string(),
  callId: z.string(),
  tool: z.string(),
  args: z.unknown(),
  /** Milliseconds the pane has to answer before the bridge times out. */
  timeoutMs: z.number().int().positive(),
});
export type ToolRequestMessage = z.infer<typeof ToolRequestMessageSchema>;

/**
 * One picture of the assistant's browser, sent after an action that changed the page. It goes to the task pane only;
 * it is never added to the conversation, saved in history, or given to the model.
 */
export const BROWSER_FRAME_MAX_BASE64 = 2_500_000;
export const BrowserFrameMessageSchema = z.object({
  type: z.literal("browser_frame"),
  requestId: z.string(),
  seq: z.number().int().nonnegative(),
  /** What the assistant just did, in words ("Clicking \"Confirm\""). Never contains typed text. */
  label: z.string().max(200),
  /** Address without query string or fragment. */
  url: z.string().max(500).optional(),
  title: z.string().max(200).optional(),
  mimeType: z.enum(["image/jpeg", "image/png"]),
  data: z.string().min(1).max(BROWSER_FRAME_MAX_BASE64),
});
export type BrowserFrameMessage = z.infer<typeof BrowserFrameMessageSchema>;

/** One file open in Word, Excel or PowerPoint with this add-in. `id` is what the assistant uses to point at it; it is not a credential. */
export const ConnectedFileSchema = z.object({
  id: z.string().min(1).max(64),
  name: z.string().max(255),
  /** Which application the file is open in. Panes and bridges from before Word and PowerPoint omit it: Excel. */
  host: HostIdSchema.default("excel"),
  /** True for the workbook this task pane belongs to. */
  current: z.boolean(),
});
export type ConnectedFile = z.infer<typeof ConnectedFileSchema>;

/** The files connected right now, current one first. Sent to every task pane whenever the list changes. */
export const ConnectedFilesMessageSchema = z.object({
  type: z.literal("connected_files"),
  files: z.array(ConnectedFileSchema).max(32),
});
export type ConnectedFilesMessage = z.infer<typeof ConnectedFilesMessageSchema>;

/**
 * Another workbook's assistant asks this one's to do something. The task pane runs it as a normal turn in its own chat
 * (its own tools, model and Ask/Auto setting) and sends `prompt` with the same `delegationId`; the bridge returns the
 * final reply to the asker.
 */
export const DelegatedPromptMessageSchema = z.object({
  type: z.literal("delegated_prompt"),
  delegationId: z.string().min(1).max(64),
  /** Who asked: the file's id and name, and the application it is open in (Excel when an older bridge omits it). */
  from: z.object({ id: z.string().min(1).max(64), name: z.string().max(255), host: HostIdSchema.optional() }),
  text: z.string().min(1).max(MAX_DELEGATED_TEXT),
});
export type DelegatedPromptMessage = z.infer<typeof DelegatedPromptMessageSchema>;

export const PingMessageSchema = z.object({
  type: z.literal("ping"),
  nonce: z.string(),
});

export const ServerMessageSchema = z.union([
  z.object({ type: z.literal("user_input_closed"), callId: z.string() }),
  HelloOkMessageSchema,
  HelloErrorMessageSchema,
  ProviderStatusMessageSchema,
  ToolRequestMessageSchema,
  BrowserFrameMessageSchema,
  ConnectedFilesMessageSchema,
  DelegatedPromptMessageSchema,
  PingMessageSchema,
  ...ProviderEventSchema.options,
]);
export type ServerMessage = z.infer<typeof ServerMessageSchema>;

export function encodeMessage(message: ClientMessageInput | ServerMessage): string {
  return JSON.stringify(message);
}

export function decodeServerMessage(raw: string): ServerMessage {
  return ServerMessageSchema.parse(JSON.parse(raw));
}

export function decodeClientMessage(raw: string): ClientMessage {
  return ClientMessageSchema.parse(JSON.parse(raw));
}
